/**
 * A minimal observable store.
 *
 * Plain TypeScript rather than a state library: the stores stay unit-testable
 * without rendering anything, and React subscribes through
 * `useSyncExternalStore`, which is built in. No dependency to justify.
 */
export interface Store<T> {
  get(): T;
  set(next: T | ((current: T) => T)): void;
  subscribe(listener: () => void): () => void;
}

export function createStore<T>(initial: T): Store<T> {
  let value = initial;
  const listeners = new Set<() => void>();

  return {
    get: () => value,
    set(next) {
      const resolved = typeof next === 'function' ? (next as (c: T) => T)(value) : next;
      if (Object.is(resolved, value)) return;
      value = resolved;
      for (const listener of listeners) listener();
    },
    subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
  };
}
